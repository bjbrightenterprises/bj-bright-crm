// Helper to compute relative dates in IST (Asia/Kolkata) as YYYY-MM-DD
export const getISTDateString = (daysOffset = 0): string => {
  const d = new Date(Date.now() + daysOffset * 86400000);
  return d.toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
};

// Helper to compute relative ISO-like timestamp in IST
export const getISTDateTimeString = (daysOffset = 0, timeHHMM = '11:00'): string => {
  const datePart = getISTDateString(daysOffset);
  return `${datePart}T${timeHHMM}:00`;
};

